const char* glyph_for(char c) {
    c = char(std::toupper(static_cast<unsigned char>(c)));
    for (const Glyph& g : kGlyphs)
        if (g.c == c) return g.rows;
    return nullptr;  // space and unknown characters draw nothing
}

